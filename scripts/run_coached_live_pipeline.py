"""One unpublished coached opening through DailyHarness.replan, not a replica.

Uses a frozen copy of the actual live runtime and its prior calendar. The
previously admitted native quality catalogue/evidence is an explicit input;
all command forecasts are regenerated by the harness at this decision time.
"""
from argparse import ArgumentParser
from dataclasses import asdict
from datetime import datetime,timedelta
from pathlib import Path
from zoneinfo import ZoneInfo
import json

from run_analysis.config import load_config
from run_analysis.adaptive.new_model_daily_harness import DailyHarness,training_metrics
from run_analysis.adaptive.quality_forecast_runtime import VERSION
from scripts.run_adaptive_lifecycle import fork_seed_plan
from scripts.replay_adaptive_search import load_decision
from scripts.check_explicit_distribution_tail import incoming_demand_trace
from scripts.research_manifest import freeze_sources
from scripts.audit_quality_starting_state import digest


def run(baseline,native,output):
    output.mkdir(exist_ok=False)
    config=load_config()
    source=baseline/'runtime'
    copied=output/'runtime'
    last=fork_seed_plan(source,copied)
    native_copy=output/'native-input'
    native_at=fork_seed_plan(native,native_copy)
    h=DailyHarness.resume(copied,config,as_of=last)
    n=DailyHarness.resume(native_copy,config,as_of=native_at)
    try:
        baseline_case=load_decision(source,len(h.events))
        if (h.stage.key!=n.stage.key or h.training_policy!=n.training_policy or
                h.scales!=n.scales or h.demand_scenario!=n.demand_scenario):
            raise ValueError('Native menu cannot replace the current live stage or fatigue policy')
        # Keep live state, prior, completed uploads, readiness, restrictions,
        # progression, frequency and ALL search allowances. Add only previously
        # admitted native commands and their explicit causal forecast evidence.
        additions={k:d for k,d in n.catalog.items() if d.workout_definition and
            d.workout_definition.get('calendar_integration')==VERSION}
        h.catalog.update(additions)
        h.coaching_contracts.update({k:n.coaching_contracts[k] for k in additions})
        h.quality_runtime=n.quality_runtime
        before=list(h.previous)
        policy=asdict(h.policy)
        manifest=freeze_sources(output/'sources.zip',config=config,entrypoint=__name__,
            inputs=(baseline/'baseline.json',source/'scenario.json',
                source/f'decision-{len(h.events):04d}.json',source/baseline_case['event']['snapshot_file'],
                native/'scenario.json',native/f'decision-{len(n.events):04d}.json'))
        result=h.replan(last+timedelta(microseconds=1),reason='unpublished_coached_live_pipeline',
            publish=False,coaching_first_purpose='sustained')
        c=result['coaching'];engine=c['engine'];program=result['program'];state=result['state']
        engine['cache'].pop(program,None)
        raw=engine['detail'](program);e=raw['evaluation']
        if not raw['decision_eligible'] or abs(e.total_cost-result['search']['cost'])>1e-12:
            raise ValueError('Final full live-path winner fails independent revalidation')
        refinements=result['search']['refinement']
        required={'coordinated_final_doses','calendar_merge_doses','native_terminal_doses'}
        if not required<=set(refinements):raise ValueError('Full live refinement path did not run')
        rank=0;rows=[]
        for day,key in program:
            d=h.catalog[key];row=dict(day=day,role=d.role,miles=d.miles)
            if d.role=='quality':
                a=c['sequence'].assignment(rank);rank+=1
                row.update(family=a.family,recipe=a.recipe,work_minutes=a.commanded_work_minutes,
                    workout=[s['instruction'] for s in d.workout_definition['structure']])
            rows.append(row)
        live=json.loads((baseline/'baseline.json').read_text())
        source_unchanged=all(digest(Path(live['live_runtime'])/p.name)==digest(p)
            for p in (source/f'decision-{len(h.events):04d}.json',source/baseline_case['event']['snapshot_file']))
        if not source_unchanged:raise ValueError('Live archived source changed during experiment')
        report=dict(entrypoint='DailyHarness.replan',source_live_decision=len(h.events),
            source_as_of=last.isoformat(),as_of=state.as_of.isoformat(),
            source_archived_cost=baseline_case['archived_cost'],
            source_live_prior=before,search_policy=policy,manifest=manifest,
            coaching_contract=asdict(c['sequence']),prior_funding=c['prior_funding'],
            selected=dict(total=e.total_cost,fatigue=e.weighted_demand_cost,delivery=e.delivery_cost,
                eligible=raw['decision_eligible']),search=result['search'],
            hard_schedule=[r for r in rows if r['day']<state.context.hard_end.isoformat()],
            full_schedule=rows,hard_end=state.context.hard_end.isoformat(),end=state.context.end.isoformat(),
            training_metrics=training_metrics(result['planned'],state.history,state.context.decision,
                (state.context.hard_end-state.context.decision).days,ZoneInfo(state.timezone)),
            key_entry=[r for r in incoming_demand_trace(e,state.context) if r['role']!='easy'],
            progression_delivery=raw.get('progression_delivery'),
            live_source_unchanged=source_unchanged,live_changed=False,published=False,
            limitations=['One opening projection, not daily/upload stability or global optimality.',
                'Native HR/load bounds and causal donor uncertainty retained; no empirical adherence validation.',
                'New coaching purpose starts with sustained work; an explicit policy assumption.',
                'No shared-running interaction, fatigue retuning, continuity penalty or forced rest day.',
                'Current live reconciled historical phases retained; no app history edits.'])
        (output/'report.json').write_text(json.dumps(report,default=str,indent=2,allow_nan=False))
        print(json.dumps({k:report[k] for k in ('selected','prior_funding','hard_schedule','training_metrics')},
            default=str,indent=2),flush=True)
    finally:
        h.sandbox.close();n.sandbox.close()


if __name__=='__main__':
    p=ArgumentParser(description=__doc__)
    p.add_argument('baseline',type=Path);p.add_argument('native',type=Path)
    p.add_argument('--output',type=Path,required=True)
    a=p.parse_args();run(a.baseline,a.native,a.output)
